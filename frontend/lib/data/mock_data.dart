  static List<Job> _rebaseSchedule(List<Job> jobs) {
    final now = DateTime.now();
    final today = DateTime(now.year, now.month, now.day);
    final scheduleStart = DateTime(2026, 9, 28);

    return jobs.map((job) {
      final originalDay = DateTime(
        job.scheduledDate.year,
        job.scheduledDate.month,
        job.scheduledDate.day,
      );
      final dayOffset = originalDay.difference(scheduleStart).inDays;
      final scheduledDay = today.add(Duration(days: dayOffset));

      DateTime onScheduledDay(DateTime time) => DateTime(
            scheduledDay.year,
            scheduledDay.month,
            scheduledDay.day,
            time.hour,
            time.minute,
          );

      return job.copyWith(
        scheduledDate: scheduledDay,
        appointmentStart: onScheduledDay(job.appointmentStart),
        appointmentEnd: onScheduledDay(job.appointmentEnd),
        eta: onScheduledDay(job.eta),
      );
    }).toList();
  }

